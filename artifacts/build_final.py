def main():
    total = 0
    for slug, en, fa, icon, fn in LANGS:
        topics = fn()
        assert len(topics) >= 100, slug
        folder = ROOT / "zaban" / slug
        folder.mkdir(parents=True, exist_ok=True)
        home = f"{slug}.html"
        for i in range(len(topics)):
            html = render_page(slug, en, home, topics, i)
            fname = home if topics[i][0] == "index" else f"{topics[i][0]}.html"
            (folder / fname).write_text(html, encoding="utf-8")
            total += 1
        print(f"{slug}: {len(topics)}", flush=True)
    (ROOT / "index.html").write_text(build_index(), encoding="utf-8")
    print("TOTAL", total + 1, flush=True)


if __name__ == "__main__":
    main()
